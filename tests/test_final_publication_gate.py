    race, battle, energy = sample_battle
    candidate = CandidateRecommendation(
        available=True,
        backend_action="DEPLOY",
        ui_call="APPLY PRESSURE",
        publication_status="PENDING_FINAL_GATE",
    )
    matrix = generate_strategy_matrix(race, battle, energy, enable_ranking=False)

    gate_res = evaluate_final_publication_gate(
        candidate=candidate,
        matrix=matrix,
        current_race_data=race,
        current_battle_data=battle,
        current_energy_state={"available": False},
    )
    assert gate_res.approved is False
    assert gate_res.lifecycle_state == CallLifecycleState.WITHHELD


