def test_adversarial_case_5_call_staleness_and_new_snapshot(sample_battle):
    """CASE 5: Previous call VALID, material state changes -> old call EXPIRED/INVALIDATED, new snapshot created."""
    race, battle, energy = sample_battle
    snap1 = compute_decision(race, battle, energy, enable_publication_gate=True)
    call1 = snap1.published_call
    assert call1 is not None

    # Advance lap
    race2 = copy.deepcopy(race)
    race2["lap"] = 19
    race2["event_time"] = "2026-03-15T05:23:45.000Z"
    race2["received_time"] = "2026-03-15T05:23:45.500Z"

    snap2 = compute_decision(race2, battle, energy, enable_publication_gate=True)
    assert snap2.decision_id != snap1.decision_id
    assert snap2.race.lap == 19


def test_adversarial_case_6_historical_replay_vs_reanalysis(sample_battle):
    """CASE 6: Historical replay loads stored snapshot beliefs; reanalysis explicitly marked."""
    race, battle, energy = sample_battle
    # 1. Historical replay run
    snap_replay = compute_decision(race, battle, energy, enable_publication_gate=True, is_reanalysis=False)
    assert snap_replay.is_reanalysis is False

    # 2. Reanalysis run on historical data
    snap_reanalysis = compute_decision(race, battle, energy, enable_publication_gate=True, is_reanalysis=True)
    assert snap_reanalysis.is_reanalysis is True
    assert snap_reanalysis.decision_id != snap_replay.decision_id
