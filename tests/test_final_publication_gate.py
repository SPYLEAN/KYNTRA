# K. New decision never mutates prior DecisionSnapshot
# ==============================================================================
def test_new_decision_never_mutates_prior_decision_snapshot(sample_battle):
    """DecisionStore guarantees append-only immutability."""
    race, battle, energy = sample_battle
    store = get_decision_store()

    snap1 = compute_decision(race, battle, energy, enable_publication_gate=True)
    dec_id_1 = snap1.decision_id
    stored1_copy = copy.deepcopy(store.get_decision(dec_id_1))

    # Advance lap and generate new decision
    race2 = copy.deepcopy(race)
    race2["lap"] = 19
    snap2 = compute_decision(race2, battle, energy, enable_publication_gate=True)
    dec_id_2 = snap2.decision_id

    assert dec_id_1 != dec_id_2
    stored1_after = store.get_decision(dec_id_1)
    assert stored1_after == stored1_copy  # First snapshot is 100% identical


